class Curso:
    def __init__(self, nome, descricao, cargaHoraria, codigo, area, periodos, disciplinas, cargaHorariaTotalMinima, cargaHorariaOptativaMinima, cargaHorariaMinimaPorPeriodo, cargaHorariaMaximaPorPeriodo, quantidadeFavoritos):
        self.nome = nome
        self.descricao = descricao
        self.cargaHoraria = cargaHoraria
        self.codigo = codigo
        self.area = area
        self.periodos = periodos
        self.disciplinas = disciplinas
        self.cargaHorariaTotalMinima = cargaHorariaTotalMinima
        self.cargaHorariaOptativaMinima = cargaHorariaOptativaMinima
        self.cargaHorariaMinimaPorPeriodo = cargaHorariaMinimaPorPeriodo
        self.cargaHorariaMaximaPorPeriodo = cargaHorariaMaximaPorPeriodo
        self.quantidadeFavoritos = quantidadeFavoritos